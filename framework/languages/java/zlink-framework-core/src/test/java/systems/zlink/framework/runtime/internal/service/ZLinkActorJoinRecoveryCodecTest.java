    @Test
    void encodingMatchesFrozenNodeAndCppVectorByteForByte() {
        UUID handoff = UUID.fromString(
            "00112233-4455-6677-8899-aabbccddeeff");
        var recovery = new ZLinkActorJoinRecoveryCodec.Recovery(
            "actor-a",
            "sample.Actor",
            handoff,
            "source-spot",
            RoutingId.from("src"),
            7,
            11,
            13,
            17,
            ZLinkActorJoinRecoveryCodec.SNAPSHOT_CONTENT_TYPE,
            "application/json",
            "{}".getBytes(java.nio.charset.StandardCharsets.UTF_8),
            "target-spot",
            RoutingId.from("dst"),
            19,
            23,
            12,
            29,
            new ZLinkActorJoinRecoveryCodec.Coordinator(
                "owner-a",
                17,
                RoutingId.from("src"),
                13,
                "store-v1"),
            new ZLinkActorJoinOperationId(31, 37),
            "application/json",
            "[]".getBytes(java.nio.charset.StandardCharsets.UTF_8));

        byte[] encoded = ZLinkActorJoinRecoveryCodec.encodeSavedWork(recovery);

        assertEquals(
            NODE_ZLJR_FROZEN_HEX,
            HexFormat.of().formatHex(encoded));
        var decoded = ZLinkActorJoinRecoveryCodec.decodeSavedWork(encoded)
            .orElseThrow();
        assertEquals(handoff, decoded.relocationId());
        assertEquals("source-spot", decoded.sourceSpotId());
        assertEquals(RoutingId.from("src"), decoded.sourceNodeRid());
        assertEquals(11, decoded.actorAuthorityOwnerGeneration());
        assertEquals(12, decoded.targetAuthorityOwnerGeneration());
        assertEquals(29, decoded.targetSpotAuthorityOwnerGeneration());
        assertEquals(
            new ZLinkActorJoinOperationId(31, 37),
            decoded.operationId());
        assertArrayEquals("{}".getBytes(
            java.nio.charset.StandardCharsets.UTF_8), decoded.request());
        assertArrayEquals("[]".getBytes(
            java.nio.charset.StandardCharsets.UTF_8), decoded.reply());
    }
